CREATE TABLE `site_inspections` (
 `id` INTEGER NOT NULL AUTO_INCREMENT,
 `projectId` INTEGER NOT NULL,
 `taskId` INTEGER NULL,
 `reportId` INTEGER NULL,
 `title` VARCHAR(150) NOT NULL,
 `inspectionDate` DATETIME(3) NOT NULL,
 `inspectorId` INTEGER NOT NULL,
 `checklist` JSON NOT NULL,
 `notes` TEXT NULL,
 `status` VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
 `createdById` INTEGER NOT NULL,
 `updatedById` INTEGER NOT NULL,
 `completedAt` DATETIME(3) NULL,
 `archivedAt` DATETIME(3) NULL,
 `version` INTEGER NOT NULL DEFAULT 1,
 `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 `updatedAt` DATETIME(3) NOT NULL,
 PRIMARY KEY (`id`), INDEX `site_inspections_projectId_inspectionDate_idx` (`projectId`,`inspectionDate`),
 CONSTRAINT `site_inspections_projectId_fkey` FOREIGN KEY (`projectId`) REFERENCES `projects`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `site_inspections_taskId_fkey` FOREIGN KEY (`taskId`) REFERENCES `site_tasks`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `site_inspections_reportId_fkey` FOREIGN KEY (`reportId`) REFERENCES `site_reports`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `site_inspections_inspectorId_fkey` FOREIGN KEY (`inspectorId`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `site_inspections_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `site_inspections_updatedById_fkey` FOREIGN KEY (`updatedById`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
